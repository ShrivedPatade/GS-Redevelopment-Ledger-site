import csv

FILE_PATH = 'data/ledger.csv'
# Read the CSV file and return its content as a list of dictionaries
def read_csv(file_path=FILE_PATH):
    """Reads a CSV file and returns its content as a list of dictionaries."""
    with open(file_path, mode='r', newline='', encoding='utf-8') as csvfile:
        reader = csv.DictReader(csvfile)
        return [row for row in reader]

# Remove 'pin' column from the CSV data
def remove_pin_column(data):
    """Removes the 'pin' column from the list of dictionaries."""
    for row in data:
        if 'pin' in row:
            del row['pin']
    return data

# Set all 'm_status' columns to 'PENDING' except 'm1_status', 'm2_status', and 'm3_status'
def set_m_status_to_pending(data):
    """Sets all 'm_status' columns to 'PENDING' except for 'm1_status', 'm2_status', and 'm3_status'."""
    for row in data:
        for key in row.keys():
            if key.startswith('m') and key.endswith('_status') and key not in ['m1_status', 'm2_status', 'm3_status']:
                row[key] = 'PENDING'
    return data

# Updame the 'name' column based on the provided list of new names
def update_names(data, new_names):
    """Updates the 'name' column based on the provided list of new names."""
    for i, row in enumerate(data):
        if i < len(new_names):
            row['name'] = new_names[i]
    return data

# Update the 'amount' columns based on the provided list of new amounts for columns ending with 'amt' 27 in each row
def update_amounts(data, new_amounts):
    """Updates the 'amount' columns based on the provided list of new amounts for columns ending with 'amt'."""
    for i, row in enumerate(data):
        if i < len(new_amounts):
            amt_values = new_amounts[i]
            amt_index = 0
            for key in row.keys():
                if key.endswith('_amt'):
                    if amt_index < len(amt_values):
                        row[key] = str(amt_values[amt_index])
                        amt_index += 1
    return data

write_path = 'data/ledger_updated.csv'
# Write the updated data to a new CSV file as UTF-8 encoded CSV
def write_csv(data, file_path=write_path):
    """Writes the updated data to a new CSV file as UTF-8 encoded CSV."""
    if not data:
        return  # No data to write

    with open(file_path, mode='w', newline='', encoding='utf-8') as csvfile:
        fieldnames = data[0].keys()
        writer = csv.DictWriter(csvfile, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(data)

